import { buildMatchPhaseFacts, buildVariantBDataBlocks } from "./shared";

import type { AdditionalSignal, AssembledContentInput, TacticalPoint } from "@/lib/llm/types";

export const PROMPT_VERSION = "recap-b@0.1.0";

export function buildGenerateRecapBPrompt(
  assembled: AssembledContentInput,
  tacticalPoints: TacticalPoint[],
  additionalSignals: AdditionalSignal[],
): string {
  const phase = buildMatchPhaseFacts(assembled);
  return [
    ...buildVariantBDataBlocks({ assembled, tacticalPoints, additionalSignals, contentType: "recap" }),
    phase,
    `終了した試合のレビューを書いてください。読者は海外ラグビーを日本語で追うファンで、この記事は試合ページに載ります。同じページに得点経過の表（時刻・得点者・種別）と最終スコアが既にあるため、本文の役割は、表では分からないこと（流れが変わった理由として言える範囲、両チームの差、次に何を見るべきか）を伝えることです。表の内容を順番に書き起こしません。

確定スコアと勝敗を前提に、結果に至る経過から「何が分かるか」を一つ選びます。派生スタッツが示すのは記録上の区間・差です。それを未確認の戦術原因に変えません。スコア推移サマリーの累計スコアは、本文でスコアを書くときにそのまま使い、自分で足し算しません。

構成は次の3節です。見出し名と順序を守ります（表示とQAが見出し名で本文を扱うため）。

# この試合の核心
150～200字を目安に、最終結果、中心となる問い、その問いへの短い答えを示します。ここでは分単位の得点経過を再演せず、読者が先を読む理由を伝えます。

# 試合全体像
勝敗を理解するのに必要な流れだけを短く整理します。全得点を時刻順に並べません。後の節で扱う局面の詳細はここで書き尽くしません。前後半、リード、追走などの変化を使う場合は、その区分と値を確認します。人名は得点や出来事の説明に必要な場合だけ使います。

# ターニングポイント
中心の問いに、具体的な根拠を使って答えます。一つの局面または比較を詳しく扱い、全体像と同じ時系列をもう一度たどりません。問い→必要な事実の比較→分かること、の順で説明します。例えば、追い上げが最終差をどこまで縮めたかは記録から検証できます。それだけで守備崩壊、接点の支配、選手の疲労を原因として断定してはいけません。カードがあっても失点の原因とは限りません。カード前後の時系列と因果を区別します。根拠が示すのが決定的な一瞬ではなく区間の差なら、そのように書きます。チームスタッツは問いに必要な項目だけ使います。締めは核心の丸写しではなく、今回の比較から読者が持ち帰れる一つの理解にします。

全体は1,200～1,600字を目安とします。最終節を分析の中心にしますが、節ごとの最低字数は設けません。根拠と構成上の必要があれば目安を超えても構いません。材料が足りない場合は、創作や反復で字数を埋めません。出力は日本語のマークダウン本文だけです。`,
  ].filter(Boolean).join("\n\n");
}
